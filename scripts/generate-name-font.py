#!/usr/bin/env python3
"""Bakes the teammate name font into src/headers/PC/cgame_mp/cg_namefont_data.h.

The glyphs come from third_party/barlow/Barlow-SemiBold.ttf (SIL Open Font
License 1.1, see third_party/barlow/OFL.txt), downloaded from
https://github.com/google/fonts/tree/main/ofl/barlow. Each one is drawn
OVERSAMPLE times larger and box-filtered down, so its edges keep their exact
coverage and its position on the texel grid.

Needs Pillow, which nothing else in the repository uses:
    python3 -m venv /tmp/fontenv && /tmp/fontenv/bin/pip install pillow
    /tmp/fontenv/bin/python3 scripts/generate-name-font.py
"""
import hashlib
import math
import pathlib

from PIL import Image, ImageDraw, ImageFont

root = pathlib.Path(__file__).resolve().parents[1]
FONT = root / 'third_party/barlow/Barlow-SemiBold.ttf'
OUTPUT = root / 'src/headers/PC/cgame_mp/cg_namefont_data.h'

# Barlow's capitals are 0.7 em, so 18 texels: about the size a name is drawn
# at 1080p, and never more than twice it at smaller sizes.
EM = 26
UNITS_PER_TEXEL = 2
OVERSAMPLE = 4
# Extra letter spacing, in ems, that makes the WWII capture's name as wide from
# its first ink to its last for its cap height: 204 px for 16. Advances round to
# half texels, so anything from 0.002 to 0.008 bakes the same font.
TRACKING = 0.005
# Transparent texels around each glyph, so filtering never reaches a neighbour.
PAD = 1
ATLAS_WIDTH = 256
ALPHA_STEP = 17


def characters():
    """Letters 0x20 to 0x7f in order, then the rest of Windows-1252."""
    codes = list(range(0x20, 0x80))
    for code in range(0x80, 0x100):
        try:
            bytes([code]).decode('cp1252')
        except UnicodeDecodeError:
            continue
        codes.append(code)
    return codes


def text_of(code):
    if code == 0x7f or code == 0xa0:
        return ' '
    return bytes([code]).decode('cp1252')


def render(font, text):
    """Returns (bitmap, left, top, advance) in texels; bitmap is None when blank."""
    advance = font.getlength(text) / OVERSAMPLE
    left, top, right, bottom = font.getbbox(text, anchor='ls')
    if right <= left or bottom <= top:
        return None, 0, 0, advance
    # The pen sits on a texel corner; the box is a texel wider on every side.
    x0 = math.floor(left / OVERSAMPLE) - 1
    y0 = math.floor(top / OVERSAMPLE) - 1
    x1 = math.ceil(right / OVERSAMPLE) + 1
    y1 = math.ceil(bottom / OVERSAMPLE) + 1
    image = Image.new('L', ((x1 - x0) * OVERSAMPLE, (y1 - y0) * OVERSAMPLE), 0)
    ImageDraw.Draw(image).text((-x0 * OVERSAMPLE, -y0 * OVERSAMPLE), text, font=font, fill=255, anchor='ls')
    bitmap = image.reduce(OVERSAMPLE)
    ink = bitmap.point(lambda v: 255 if round(v / ALPHA_STEP) else 0).getbbox()
    if not ink:
        return None, 0, 0, advance
    box = (ink[0] - PAD, ink[1] - PAD, ink[2] + PAD, ink[3] + PAD)
    return bitmap.crop(box), x0 + box[0], y0 + box[1], advance


def main():
    font = ImageFont.truetype(str(FONT), EM * OVERSAMPLE)
    notdef = render(font, '\U0010ffff')[0].tobytes()
    glyphs = []
    for code in characters():
        text = text_of(code)
        bitmap, left, top, advance = render(font, text)
        if bitmap and bitmap.tobytes() == notdef:
            raise SystemExit(f'{FONT.name} has no glyph for {text!r}')
        glyph = {'letter': code, 'bitmap': bitmap, 'x0': left * UNITS_PER_TEXEL, 'y0': top * UNITS_PER_TEXEL,
                 'dx': round((advance + TRACKING * EM) * UNITS_PER_TEXEL), 'width': 0, 'height': 0, 'ax': 0, 'ay': 0}
        if bitmap:
            glyph['width'], glyph['height'] = bitmap.size
        for key, low, high in (('x0', -128, 127), ('y0', -128, 127), ('dx', 0, 255)):
            if not low <= glyph[key] <= high:
                raise SystemExit(f'{text!r} {key} {glyph[key]} does not fit a Glyph')
        if glyph['width'] * UNITS_PER_TEXEL > 255 or glyph['height'] * UNITS_PER_TEXEL > 255:
            raise SystemExit(f'{text!r} is too large for a Glyph')
        glyphs.append(glyph)

    # Shelves of glyphs sorted by height, tallest first.
    x = y = shelf = 0
    for glyph in sorted((g for g in glyphs if g['bitmap']), key=lambda g: (-g['height'], -g['width'], g['letter'])):
        if x + glyph['width'] > ATLAS_WIDTH:
            x, y, shelf = 0, y + shelf, 0
        glyph['ax'], glyph['ay'] = x, y
        x += glyph['width']
        shelf = max(shelf, glyph['height'])
    height = y + shelf
    atlas = Image.new('L', (ATLAS_WIDTH, height), 0)
    for glyph in glyphs:
        if glyph['bitmap']:
            atlas.paste(glyph['bitmap'], (glyph['ax'], glyph['ay']))
    pixels = atlas.load()

    digest = hashlib.sha256(FONT.read_bytes()).hexdigest()
    lines = [
        '/* Generated by scripts/generate-name-font.py; do not edit.',
        f' * Barlow SemiBold, third_party/barlow/Barlow-SemiBold.ttf (SHA-256 {digest}).',
        ' * Copyright 2017 The Barlow Project Authors (https://github.com/jpt/barlow),',
        ' * SIL Open Font License 1.1, see third_party/barlow/OFL.txt. */',
        '#ifndef CG_NAMEFONT_DATA_H',
        '#define CG_NAMEFONT_DATA_H',
        '',
        f'#define CG_NAME_FONT_ATLAS_WIDTH {ATLAS_WIDTH}',
        f'#define CG_NAME_FONT_ATLAS_HEIGHT {height}',
        '/* Offsets and advances count font units, UNITS_PER_TEXEL to a texel of the',
        ' * atlas; PIXEL_HEIGHT units make the em. */',
        f'#define CG_NAME_FONT_UNITS_PER_TEXEL {UNITS_PER_TEXEL}',
        f'#define CG_NAME_FONT_PIXEL_HEIGHT {EM * UNITS_PER_TEXEL}',
        f'#define CG_NAME_FONT_GLYPH_COUNT {len(glyphs)}',
        '/* A digit of the atlas times this is the texel\'s alpha. */',
        f'#define CG_NAME_FONT_ALPHA_STEP {ALPHA_STEP}',
        '',
        'typedef struct CG_NameFontGlyph {',
        '    unsigned short letter;',
        '    /* From the pen on the baseline to the bitmap\'s top left corner. */',
        '    signed char x0;',
        '    signed char y0;',
        '    unsigned char dx;',
        '    /* Texels of the atlas. */',
        '    unsigned char width;',
        '    unsigned char height;',
        '    unsigned short atlasX;',
        '    unsigned short atlasY;',
        '} CG_NameFontGlyph;',
        '',
        '/* Letters 0x20 to 0x7f in order, then the rest of Windows-1252 ascending,',
        ' * the order R_GetCharacterGlyph searches. */',
        'static const CG_NameFontGlyph cg_nameFontGlyphs[CG_NAME_FONT_GLYPH_COUNT] = {',
    ]
    for glyph in glyphs:
        lines.append('    {{ 0x{letter:02x}, {x0}, {y0}, {dx}, {width}, {height}, {ax}, {ay} }},'.format(**glyph))
    lines += [
        '};',
        '',
        '/* A row of the atlas per string, a hex digit of alpha per texel. */',
        'static const char *const cg_nameFontAtlas[CG_NAME_FONT_ATLAS_HEIGHT] = {',
    ]
    for row in range(height):
        digits = ''.join('%x' % min(15, round(pixels[column, row] / ALPHA_STEP)) for column in range(ATLAS_WIDTH))
        lines.append(f'    "{digits}",')
    lines += ['};', '', '#endif', '']
    OUTPUT.write_text('\n'.join(lines))
    print(f'{OUTPUT.relative_to(root)}: {len(glyphs)} glyphs, {ATLAS_WIDTH}x{height} atlas')


if __name__ == '__main__':
    main()
