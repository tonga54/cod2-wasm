#!/usr/bin/env python3
"""Embeds the faces that every CoD2 font is redrawn in into
src/headers/PC/gfx_d3d/r_font_wwii_data.h, for r_font_wwii.c to rasterize.

The faces are third_party/barlow/Barlow-{Medium,SemiBold,Bold,Regular}.ttf (SIL
Open Font License 1.1, see third_party/barlow/OFL.txt), downloaded from
https://github.com/google/fonts/tree/main/ofl/barlow. Each is cut down to the
letters of Windows-1252, without hinting and without the layout tables, which
the renderer does not read.

Needs fontTools, which nothing else in the repository uses:
    python3 -m venv /tmp/fontenv && /tmp/fontenv/bin/pip install fonttools
    /tmp/fontenv/bin/python3 scripts/generate-wwii-fonts.py
"""
import hashlib
import io
import pathlib

from fontTools import subset
from fontTools.ttLib import TTFont

root = pathlib.Path(__file__).resolve().parents[1]
FACES = [('Medium', 'r_wwiiFontMedium'), ('SemiBold', 'r_wwiiFontSemiBold'), ('Bold', 'r_wwiiFontBold'),
         ('Regular', 'r_wwiiFontRegular')]
OUTPUT = root / 'src/headers/PC/gfx_d3d/r_font_wwii_data.h'
BYTES_PER_LINE = 24


def codepoints():
    """The letters of Windows-1252 that the fonts draw."""
    points = set(range(0x20, 0x7f))
    for code in range(0x80, 0x100):
        try:
            points.add(ord(bytes([code]).decode('cp1252')))
        except UnicodeDecodeError:
            continue
    return sorted(points)


def cut(path):
    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.drop_tables += ['GSUB', 'GPOS', 'GDEF', 'kern', 'DSIG', 'STAT', 'gasp', 'prep', 'fpgm', 'cvt ']
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    options.recalc_timestamp = False
    font = TTFont(str(path), recalcTimestamp=False)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints())
    subsetter.subset(font)
    missing = [hex(c) for c in codepoints() if c not in font.getBestCmap()]
    if missing:
        raise SystemExit(f'{path.name} has no glyph for {missing}')
    buffer = io.BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def main():
    lines = [
        '/* Generated by scripts/generate-wwii-fonts.py; do not edit.',
        ' * Barlow Medium, SemiBold, Bold and Regular from third_party/barlow/, cut',
        ' * down to the letters of Windows-1252:',
    ]
    arrays = []
    for weight, symbol in FACES:
        path = root / f'third_party/barlow/Barlow-{weight}.ttf'
        data = cut(path)
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f' *   Barlow-{weight}.ttf, SHA-256 {digest}.')
        arrays.append(f'static const unsigned char {symbol}[{len(data)}] = {{')
        for start in range(0, len(data), BYTES_PER_LINE):
            arrays.append('    ' + ','.join(str(b) for b in data[start:start + BYTES_PER_LINE]) + ',')
        arrays.append('};')
        arrays.append('')
    lines += [
        ' * Copyright 2017 The Barlow Project Authors (https://github.com/jpt/barlow),',
        ' * SIL Open Font License 1.1, see third_party/barlow/OFL.txt. */',
        '#ifndef R_FONT_WWII_DATA_H',
        '#define R_FONT_WWII_DATA_H',
        '',
    ] + arrays + ['#endif', '']
    OUTPUT.write_text('\n'.join(lines))
    print(f'{OUTPUT.relative_to(root)}: {", ".join(w for w, _ in FACES)}')


if __name__ == '__main__':
    main()
